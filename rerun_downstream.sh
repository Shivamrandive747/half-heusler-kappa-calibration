# Optional slice for runs longer than one sitting: FROM=<first step> TO=<last step>, 0-based and
# inclusive (e.g. FROM=0 TO=27 ./rerun_downstream.sh, then FROM=28 ./rerun_downstream.sh). The order
# is still the dependency order above; a slice never skips a step it depends on.
FROM=${FROM:-0}
TO=${TO:-$(( ${#STEPS[@]} - 1 ))}
STEPS=("${STEPS[@]:$FROM:$(( TO - FROM + 1 ))}")
fail=0
for s in "${STEPS[@]}"; do
  t0=$(date +%s)
  # a step may carry arguments; the log name is the step text, flattened
  log="/tmp/rerun_$(echo "$s" | tr ' /' '__').log"
  # shellcheck disable=SC2086
  "$PY" $s > "$log" 2>&1
  rc=$?
  t1=$(date +%s)
  printf "%-36s exit=%d  %4ds\n" "$s" "$rc" "$((t1 - t0))"
  [ "$rc" -ne 0 ] && fail=$((fail + 1)) && tail -5 "$log" | sed 's/^/      /'
done
echo "failures: $fail"
