#!/usr/bin/env bash
# Re-run the whole analysis chain, in dependency order, and report each step's exit status.
#
#   ./rerun_downstream.sh
#
# Anything that changes the in-domain set, a family constant, the global fit or the calculation
# rules needs ALL of this, in THIS order.
#
# ORDER MATTERS, AND GETTING IT WRONG IS SILENT. compute_conformal_indomain.py writes the interval
# bands that make_paper_predictions.py and compute_conditional.py read. An earlier version of this
# script ran it after them, so every prediction table carried the PREVIOUS run's intervals: the
# predicted values were right and the lo50/hi50/lo90/hi90 columns were stale, with nothing raising an
# error. The bands in turn read family_calibration.json, so the order is fixed as:
#     family calibration -> reference audit -> deployed route -> interval bands -> predictions
#     -> everything that reads the predictions -> figures -> numbers registry -> release
# RELEASE COPY, generated by make_release.py from the working copy's rerun_downstream.sh.
# Paths mapped to analysis/ corpus/ checks/ paper/; 8 step(s) commented out (reason on
# each line). Run from the repository root:  PY=python bash rerun_downstream.sh
set -u
cd "$(dirname "$0")" || exit 1
PY=${PY:-python}   # release: any interpreter with the requirements installed
export PYTHONIOENCODING=utf-8

# THE BLIND-TEST SEEDS COME FIRST. Until 2026-10-04 this chain started at family_calibration.py and
# never regenerated the five seed files the headline is computed from, so they stayed frozen at
# 2026-09-06 while the training set changed under them (rerun on identical code: 34.7% vs the stored
# 37.2%). Seed 0 is written twice because compute_seed_averaged.py reads it from target_blind_test.csv
# and compute_nested_across_seeds.py from paper/evidence; the run is deterministic.
#
# THE OUT-OF-CHAIN PRODUCERS (FIXPASS C1, 2026-10-05). Every script whose output the paper or the
# registry quotes is now a step. Until then the structure-only / surrogate / calibrated-new / Bi-Pt
# tables, the generator validation, the twin and shared-constant tests, the inter-lab ceiling and the
# model comparison were run by hand and went stale silently: on 2026-10-05 every structure-only,
# surrogate, series-gap and Bi-Pt product still carried the withdrawn shared constant c=0.51, p=0.80
# (make_paper_numbers now refuses to write the registry when that happens). Their order:
#   build_cluster_support       training pool only; FIRST, because compute_nested_across_seeds and
#                               extend_blind_test read cluster_support_real.csv
#   validate_bte_generator      -> bte_generator_validation.csv (read by twins, structure-only, Bi-Pt)
#   test_chemical_twins         -> chemical_twins.csv (Bi-Pt twin ratio, registry)
#   test_shared_constant        -> shared_constant_test.json (labels of the 12 and Bi-Pt tables)
#   test_family_form_nested     -> family_form_nested.json
#   predict_bipt_theory
#   compute_interlab_ceiling, compute_semiempirical_vs_bte, compare_models_production -> fig07_model
# They need family_calibration.json and the shared constant, so they follow compute_conformal_indomain.
# Inputs NOT regenerated here (upstream, rerun by hand when their own inputs change):
#   the optimade_*.json structure caches.
STEPS=(
  analysis/build_cluster_support.py
  "analysis/run_target_blind_test.py --seed 0"
  "analysis/run_target_blind_test.py --seed 0 --out paper/evidence/blind_d2_s0.csv"
  "analysis/run_target_blind_test.py --seed 1 --out paper/evidence/blind_d2_s1.csv"
  "analysis/run_target_blind_test.py --seed 2 --out paper/evidence/blind_d2_s2.csv"
  "analysis/run_target_blind_test.py --seed 3 --out paper/evidence/blind_d2_s3.csv"
  "analysis/run_target_blind_test.py --seed 4 --out paper/evidence/blind_d2_s4.csv"
  analysis/family_calibration.py
